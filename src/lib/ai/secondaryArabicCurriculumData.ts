/**
 * دالة البحث السريع واسترجاع الدروس من قاعدة بيانات المنهاج المحلي
 */
export function findCurriculumLesson(params: {
  grade?: string;
  activity?: string;
  topic?: string;
  unit?: string;
}): CurriculumLessonItem | null {
  const normalizedTopic = (params.topic || '').trim().toLowerCase();
  const normalizedActivity = (params.activity || '').trim();
  const normalizedGrade = (params.grade || '').trim();

  // 1. المطابقة الدقيقة للعنوان
  let match = SECONDARY_ARABIC_CURRICULUM.find(item => {
    const topicMatch = item.topic.toLowerCase().includes(normalizedTopic) || normalizedTopic.includes(item.topic.toLowerCase());
    const activityMatch = !normalizedActivity || item.activity === normalizedActivity;
    const gradeMatch = !normalizedGrade || item.grade.includes(normalizedGrade) || normalizedGrade.includes(item.grade);
    return topicMatch && (activityMatch || gradeMatch);
  });

  if (match) return match;

  // 2. المطابقة بالكلمات المفتاحية في الموضوع
  const keywords = normalizedTopic.split(/\s+/).filter(w => w.length > 2);
  if (keywords.length > 0) {
    match = SECONDARY_ARABIC_CURRICULUM.find(item => {
      const hasKeyword = keywords.some(k => item.topic.includes(k) || item.theme.includes(k) || item.unitTitle.includes(k));
      const activityMatch = !normalizedActivity || item.activity === normalizedActivity;
      return hasKeyword && activityMatch;
    });
  }

  if (match) return match;

  // 3. المطابقة بالنشاط والمستوى فقط
  if (normalizedActivity && normalizedGrade) {
    match = SECONDARY_ARABIC_CURRICULUM.find(item => 
      item.activity === normalizedActivity && (item.grade.includes(normalizedGrade) || normalizedGrade.includes(item.grade))
    );
  }

  return match || null;
}
